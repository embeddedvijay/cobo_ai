from indic_transliteration import sanscript
from indic_transliteration.sanscript import transliterate
import re
import jellyfish 
from fuzzywuzzy import fuzz
from datetime import datetime


def is_devanagari(text)->bool:
        return bool(re.search(r'[\u0900-\u097F]', text))

def get_overall_markets(msg:str)->[set,str]:
    markets = set()
    for k,v in market_names.items():

        if any(_mname in msg for _mname in v):
            markets.add(k)
            print("local",k)
            for _mname in v:
                msg = msg.replace(_mname,f" {k} ")
            continue

        for _word in re.findall(r'[A-Za-z]+|[\u0900-\u097F]+',msg):
            if is_devanagari(_word):
                _name = transliterate(_word, sanscript.DEVANAGARI, sanscript.ITRANS)
            else:
                _name = _word

            if len(_word)>2 and any(fuzz.ratio(jellyfish.soundex(_name),jellyfish.soundex(_mname))>80 for _mname in v ):
                print("jellyfish",k,_name)
                markets.add(k)
                msg = msg.replace(_word,f" {k} ")
                continue
    return markets,msg



def get_market_n_message(msg:str)->list:
    _markets,_msg = get_overall_markets(msg.upper())

    return list(_markets)

def remove_date(_msg:str)->str:
    current_date_strs = {
        *[datetime.now().strftime(fmt) for fmt in ("%d/%m/%y", "%m/%d/%y", "%d/%m/%Y","%d/%m")],
        f'{int(datetime.now().strftime('%d'))}/{int(datetime.now().strftime('%m'))}/{datetime.now().strftime('%y')}',
        f'{(datetime.now().strftime('%d'))}/{int(datetime.now().strftime('%m'))}/{datetime.now().strftime('%y')}',
        f'{int(datetime.now().strftime('%d'))}/{(datetime.now().strftime('%m'))}/{datetime.now().strftime('%y')}',
        f'{int(datetime.now().strftime('%d'))}/{int(datetime.now().strftime('%m'))}/{datetime.now().strftime('%Y')}',
        f'{(datetime.now().strftime('%d'))}/{int(datetime.now().strftime('%m'))}/{datetime.now().strftime('%Y')}',
        f'{int(datetime.now().strftime('%d'))}/{(datetime.now().strftime('%m'))}/{datetime.now().strftime('%Y')}'
    }
    translation_table = str.maketrans('०१२३४५६७८९', '0123456789')
    _msg = _msg.translate(translation_table)

    for strdate in current_date_strs:
        _msg = _msg.replace(strdate,"")
    return _msg


def market_message_dict(msg:str)->dict:
    msg_dict = dict()
    _markets,_msg = get_overall_markets(msg.upper())

    _msg = remove_date(_msg)

    def market_in(line:str)->list:
        return [mkt for mkt in market_names.keys() if mkt in line]
    def nums_in(line:str)->list:
        return re.findall(r'\d+',line)
    
    if len(_markets)==1:
        msg_dict[list(_markets)[0] ] = _msg
    else:
        _lmarket = []
        _lmsg = ''
        lines = _msg.split('\n')

        def set_mkt_dict(line:str):
            nonlocal _lmarket
            nonlocal _lmsg
            for mkt in _lmarket:
                if msg_dict.get(mkt,False):
                    msg_dict[mkt] += _lmsg
                else:
                    msg_dict[mkt] = _lmsg
            _lmsg = line
            _lmarket = []


        for linenum,line in enumerate(lines):
            line_mkt_list = market_in(line)
            msg_nums = nums_in(_lmsg)
            _lmsg += '\n' + line

            if line_mkt_list:
                _lmarket.extend(line_mkt_list)
                if linenum<(len(lines)-1):
                    if market_in(lines[linenum+1]): 
                        continue

                if _lmarket and msg_nums :
                    if _lmarket:
                        line = ''
                    set_mkt_dict(line)
                elif msg_nums and not _lmarket:
                    if linenum<(len(lines)-1):
                        if nums_in(lines[linenum+1]):
                            set_mkt_dict('')  
                continue
            if linenum<(len(lines)-1) and (not line_mkt_list) and msg_nums:
                if market_in(lines[linenum+1]) and _lmarket:
                    set_mkt_dict('')
            
        set_mkt_dict('')
    if len(msg_dict.keys()) != len(_markets):
        msg_dict = {}
    if not all(len(nums_in(v))>2 for v in msg_dict.values()):
        msg_dict = {}
    if msg_dict and ('CANCEL' in msg.upper()):
        for k in list(msg_dict.keys()):
            msg_dict[k] += '\n CANCEL'
    return msg_dict

                        


        
